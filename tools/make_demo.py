def make_audio(dst: Path, seconds: int):
    """Тихий шум нужной длины — плееру есть что показывать."""
    subprocess.run([FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi",
                    "-i", f"anoisesrc=color=brown:amplitude=0.015:duration={seconds}",
                    "-ac", "1", "-c:a", "aac", "-b:a", "32k", "-movflags", "+faststart", str(dst)], check=True)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    init()
    for i, c in enumerate(CALLS + [PROCESSING]):
        call_id = f"{i + 1:02d}" + "d" * 30
        d = config.CALLS_DIR / call_id
        d.mkdir(parents=True)
        make_audio(d / "audio.m4a", c["duration"])
        done = "transcript" in c
        row = dict(id=call_id, created_at=c["created"], updated_at=c["created"] + 120, contact=c["contact"],
                   template=c["template"], kind=c.get("kind", ""), original_name=c["original"], source_ext="m4a",
                   origin=c["origin"], size_bytes=c["duration"] * 16000, duration_sec=c["duration"],
                   status="done" if done else "processing", redo="summary" if done else "all",
                   progress=100 if done else c["progress"], message="Готово" if done else c["message"],
                   models=MODEL if done else "", notified=1 if done else 0,
                   short_summary=summarize.short_summary(c["summary"]) if done else "")
        if done:
            (d / "transcript.txt").write_text(c["transcript"], encoding="utf-8")
            (d / "summary.md").write_text(c["summary"], encoding="utf-8")
            header = summary_header(row, c["kind"], c["duration"])
            make_docx.build_docx(header + c["summary"], d / "summary.docx", transcript=c["transcript"])
        with db() as con:
            con.execute(f"INSERT INTO calls({', '.join(row)}) VALUES({', '.join('?' * len(row))})",
                        tuple(row.values()))
        print("+", c["contact"] or "без имени")
    # Чтобы настройки показывали подключённый Telegram
    set_setting("telegram_chat_id", "1")
    set_setting("telegram_bot_username", "kahman_transcriber_bot")
    print(f"Готово: {DEMO_DIR}")


if __name__ == "__main__":
    main()
