def ago(days: float, hour: int, minute: int) -> int:
    """Время days дней назад в заданный час (по часовому поясу сайта)."""
    from datetime import datetime, timedelta
    base = datetime.fromtimestamp(NOW, config.TZ).replace(hour=hour, minute=minute, second=0, microsecond=0)
