"""Итог разговора по готовой расшифровке через Gemini.

Запуск:
    python summarize.py "results/Созвон/транскрипция.txt" [--template cold|client|auto] [--context "..."]

Рядом с расшифровкой появятся итог.md и итог.docx (итог + полная расшифровка).
Сайт вызывает summarize() напрямую — см. app/worker.py.
"""
import argparse
import re
import sys
from pathlib import Path

from transcribe import GeminiError, generate_with_fallback, make_client

# Что можно выбрать при загрузке
TEMPLATES = {
    "auto": "Авто",
    "cold": "Холодный звонок",
    "client": "Созвон с заказчиком",
}
# Каким получился итог (в режиме «Авто» тип выбирает модель)
KINDS = {
    "cold": "Холодный звонок",
    "client": "Созвон с заказчиком",
    "general": "Разговор",
}

COMMON_RULES = """Ты пишешь итог телефонного разговора по его дословной расшифровке. Разговор ведёт владелец
веб-студии (сайты под ключ и настройка рекламы в Яндекс Директе).

Правила:
- Только то, что действительно прозвучало. Ничего не додумывай. Чего не обсуждали — так и пиши: «не обсуждали».
- Если не уверен (неразборчиво, двусмысленно) — помечай «(неуверенно)».
- Пиши по-русски, коротко и по делу, без воды и общих слов. Цифры, сроки, суммы, имена — точно как в разговоре.
- Разметка — только такая: «## Раздел», «### Подраздел», списки «- », нумерация «1. », цитаты «> »,
  таблицы «| a | b |» со строкой «|---|---|», **жирный** внутри строки. Заголовок первого уровня «# » не пиши.
- Не добавляй вступлений и заключений от себя — только разделы ниже.
"""

COLD = """Это холодный звонок: владелец студии звонит потенциальному клиенту. Разделы:

## Коротко
2–3 предложения: с кем говорили, чем закончился звонок.

## Собеседник
- Компания и чем занимается, должность или роль собеседника, кто принимает решения — только прозвучавшее.

## Интерес
**Высокий / средний / низкий / нет** — и одной-двумя фразами почему.

## Потребности и боли
- Что сейчас с сайтом, рекламой, заявками; что не устраивает.

## Возражения
| Возражение | Как ответили | Снято? |
|---|---|---|

Если возражений не было — строка «Возражений не было».

## Договорённости и следующий шаг
- Что и когда делаем мы, что обещал собеседник. Даты и время — если звучали.

## Оценка лида
**Горячий / тёплый / холодный / не наш клиент** — коротко почему.

## Что улучшить в разговоре
1–3 конкретных совета владельцу студии: что можно было спросить или сказать иначе. С таймкодом [Ч:ММ:СС], если совет про конкретный момент.
"""

CLIENT = """Это созвон с заказчиком или потенциальным заказчиком (бриф, обсуждение проекта, согласование). Разделы:

## Коротко
3–5 предложений: цель созвона и главное решение.

## 1. Контекст
Компания, история, ситуация, откуда клиенты — только прозвучавшее.

## 2. …
Тематические разделы по содержанию разговора (направления, преимущества, клиенты, реклама, сроки, бюджет — что обсуждали).
Если есть сравнение — таблица. Нумерация разделов сквозная.

## N. Следующие шаги
### С нашей стороны
- …
### Со стороны собеседника
- …
(со сроками, если звучали)

## N+1. Открытые вопросы
- …

## N+2. Цитаты
> «дословно» [Ч:ММ:СС]
3–6 самых полезных цитат собеседника: формулировки, которые пригодятся для текстов сайта и рекламы.
"""

GENERAL = """Разговор не похож ни на холодный звонок, ни на созвон по проекту. Разделы:

## Коротко
2–4 предложения: о чём разговор и чем закончился.

## Главное
- Ключевые факты и решения.

## Договорённости
- Кто, что и когда делает.

## Открытые вопросы
- …
"""

AUTO = f"""Сначала определи тип разговора и напиши ПЕРВОЙ строкой ровно одно из:
Тип: cold
Тип: client
Тип: general

cold — холодный звонок потенциальному клиенту (знакомство, предложение услуг, выход на ЛПР).
client — разговор с заказчиком по проекту: бриф, обсуждение сайта или рекламы, согласование, сроки, оплата.
general — всё остальное.

Затем, со следующей строки, напиши итог по разделам выбранного типа.

=== Тип cold ===
{COLD}
=== Тип client ===
{CLIENT}
=== Тип general ===
{GENERAL}"""

PROMPTS = {"cold": COLD, "client": CLIENT, "auto": AUTO}


def summarize(transcript: str, template: str = "auto", context: str = "", log=None) -> tuple[str, str, str]:
    """Возвращает (итог в markdown, фактический тип cold/client/general, модель)."""
    if template not in PROMPTS:
        template = "auto"
    prompt = COMMON_RULES + "\n" + PROMPTS[template]
    if context:
        prompt += f"\nУчастники разговора: {context}\n"
    prompt += "\n=== Расшифровка ===\n" + transcript
    text, model = generate_with_fallback(make_client(), [prompt], "итог", log)
    text = text.strip()

    kind = template
    m = re.match(r"^\s*Тип:\s*(cold|client|general)\s*\n", text)
    if m:
        kind = m[1]
        text = text[m.end():]
    elif template == "auto":
        kind = "general"
    # Модель иногда оборачивает ответ в ```markdown … ``` — снимаем
    text = re.sub(r"^```(?:markdown|md)?\s*\n|\n```\s*$", "", text.strip())
    return text.strip() + "\n", kind, model


def short_summary(md: str, limit: int = 700) -> str:
    """Текст раздела «Коротко» — для уведомления и списка звонков."""
    m = re.search(r"^##\s*(?:\d+\.\s*)?Коротко\s*\n(.*?)(?=^##\s|\Z)", md, re.S | re.M)
    text = (m[1] if m else md).strip()
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"^[-*>]\s*", "", text, flags=re.M)
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= limit else text[: limit - 1].rsplit(" ", 1)[0] + "…"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    from make_docx import build_docx

    ap = argparse.ArgumentParser()
    ap.add_argument("transcript")
    ap.add_argument("--template", default="auto", choices=list(PROMPTS))
    ap.add_argument("--context", default="")
    args = ap.parse_args()

    src = Path(args.transcript)
    transcript = src.read_text(encoding="utf-8")
    try:
        md, kind, model = summarize(transcript, args.template, args.context)
    except GeminiError as e:
        sys.exit(str(e))
    md = f"# Итог разговора\n_{KINDS.get(kind, 'Разговор')} · {model}_\n\n" + md
    (src.parent / "итог.md").write_text(md, encoding="utf-8")
    build_docx(md, src.parent / "итог.docx", transcript)
    print(f"Готово: {src.parent / 'итог.docx'}")


if __name__ == "__main__":
    main()
